def encrypt(num: int) -> int:
    # Маска для чётных битов (0, 2, 4, ..., 14)
    even_mask = 0x5555  # бинарно: 0101 0101 0101 0101
    # Маска для нечётных битов (1, 3, 5, ..., 15)
    odd_mask = 0xAAAA  # бинарно: 1010 1010 1010 1010

    # Получаем биты на чётных позициях и сдвигаем их влево на 1 (на нечётные позиции)
    even_bits_shifted = (num & even_mask) << 1
    # Получаем биты на нечётных позициях и сдвигаем их вправо на 1 (на чётные позиции)
    odd_bits_shifted = (num & odd_mask) >> 1

    # Объединяем сдвинутые биты — соседние биты поменялись местами
    return even_bits_shifted | odd_bits_shifted
